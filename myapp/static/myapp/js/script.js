document.addEventListener('DOMContentLoaded', function () {
  const track = document.getElementById('galleryTrack');
  const viewport = document.getElementById('galleryViewport');
  const prevBtn = document.getElementById('galleryPrev');
  const nextBtn = document.getElementById('galleryNext');
  const dotsWrap = document.getElementById('galleryDots');

  if (!track || !viewport) return;

  const items = Array.from(track.children);
  const totalItems = items.length;

  let visibleCount = getVisibleCount();
  let currentIndex = 0;
  let autoSlideTimer = null;
  const AUTO_SLIDE_INTERVAL = 3000; // 3 seconds

  function getVisibleCount() {
    const width = window.innerWidth;
    if (width <= 600) return 1;
    if (width <= 992) return 2;
    return 3;
  }

  function maxIndex() {
    // last valid index so track doesn't scroll past the final set of images
    return Math.max(totalItems - visibleCount, 0);
  }

  function updateSlidePosition() {
    const itemWidth = viewport.clientWidth / visibleCount;
    track.style.transform = `translateX(-${currentIndex * itemWidth}px)`;
    updateDots();
  }

  function goToIndex(index) {
    const max = maxIndex();
    if (index > max) index = 0;       // loop back to start
    if (index < 0) index = max;       // loop to end
    currentIndex = index;
    updateSlidePosition();
  }

  function nextSlide() {
    goToIndex(currentIndex + 1);
  }

  function prevSlide() {
    goToIndex(currentIndex - 1);
  }

  function buildDots() {
    if (!dotsWrap) return;
    dotsWrap.innerHTML = '';
    const dotCount = maxIndex() + 1;
    for (let i = 0; i < dotCount; i++) {
      const dot = document.createElement('button');
      dot.classList.add('gallery-dot');
      if (i === currentIndex) dot.classList.add('active');
      dot.addEventListener('click', () => {
        goToIndex(i);
        resetAutoSlide();
      });
      dotsWrap.appendChild(dot);
    }
  }

  function updateDots() {
    if (!dotsWrap) return;
    const dots = dotsWrap.querySelectorAll('.gallery-dot');
    dots.forEach((dot, i) => {
      dot.classList.toggle('active', i === currentIndex);
    });
  }

  function startAutoSlide() {
    autoSlideTimer = setInterval(nextSlide, AUTO_SLIDE_INTERVAL);
  }

  function resetAutoSlide() {
    clearInterval(autoSlideTimer);
    startAutoSlide();
  }

  // Button events
  if (nextBtn) {
    nextBtn.addEventListener('click', () => {
      nextSlide();
      resetAutoSlide();
    });
  }

  if (prevBtn) {
    prevBtn.addEventListener('click', () => {
      prevSlide();
      resetAutoSlide();
    });
  }

  // Pause on hover (desktop UX)
  viewport.addEventListener('mouseenter', () => clearInterval(autoSlideTimer));
  viewport.addEventListener('mouseleave', startAutoSlide);

  // Recalculate on resize (debounced)
  let resizeTimer;
  window.addEventListener('resize', () => {
    clearTimeout(resizeTimer);
    resizeTimer = setTimeout(() => {
      visibleCount = getVisibleCount();
      currentIndex = 0;
      buildDots();
      updateSlidePosition();
    }, 200);
  });

  // Init
  buildDots();
  updateSlidePosition();
  startAutoSlide();
});




